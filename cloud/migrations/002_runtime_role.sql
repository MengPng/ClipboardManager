BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='clipboardmanager_app') THEN
    CREATE ROLE clipboardmanager_app NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
  END IF;
END $$;

GRANT USAGE ON SCHEMA public TO clipboardmanager_app;
GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA public TO clipboardmanager_app;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO clipboardmanager_app;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA public TO clipboardmanager_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT,INSERT,UPDATE,DELETE ON TABLES TO clipboardmanager_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE,SELECT ON SEQUENCES TO clipboardmanager_app;

COMMIT;
